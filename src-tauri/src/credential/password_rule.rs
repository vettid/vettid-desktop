//! The passphrase rule: the vault's password rule (VAULT-MESSAGING §11.14.7),
//! ported from vettid-vault `vms/recovery/password.go` at `5deefac` so a
//! passphrase gets the same verdict here as in the vault and the apps (the
//! Android and iOS ports follow the same file).
//!
//! A passphrase must, in this order:
//! 1. have at least 12 characters (Unicode scalar values, after NFC);
//! 2. not be one character repeated;
//! 3. not be on the common-password list (compared with ASCII letters in
//!    lower case);
//! 4. (the vault's "same as the PIN" has no counterpart here: the desktop has
//!    no PIN;)
//! 5. need at least [`APP_FLOOR`] guesses by the estimator below.
//!
//! The apps use 2 × 10¹⁰ guesses where the vault uses 10¹⁰ (§11.14.7: "the
//! app runs the same model with a slightly higher threshold"), so a passphrase
//! accepted here would be accepted by the vault too.
//!
//! In `passwords/`, the two lists (`common-passwords.txt`,
//! `estimator-words.txt`) and `verdicts.json` are byte-for-byte copies of the
//! vault's at `5deefac`; the lists' SHA-256 is pinned in the tests.
//! `estimator-vectors.json` was generated by running the vault's own Go code
//! (Go 1.26, Unicode 15.0.0) over 1,398 passwords; the tests check that this
//! port gives the same guess counts and verdicts for each.
//!
//! Port notes. Go works on runes; Rust's `char`s are the same code points for
//! valid UTF-8. Go's `unicode.ToLower` and `ToUpper` are Unicode's simple,
//! one-to-one mappings; `lower` and `upper` below give the same. Go's
//! `unicode.IsDigit` is the general category Nd, taken from Go 1.26's tables
//! (`ND`, Unicode 15.0.0). Go's `unicode.IsUpper` is Lu, where Rust's
//! `is_uppercase` also counts Other_Uppercase; it is only used for a
//! dictionary match, and a dictionary match needs every character to lower
//! to ASCII, where the two agree.

use std::collections::HashMap;
use std::sync::OnceLock;

/// The apps' guessability floor (the vault's is 10¹⁰).
pub(crate) const APP_FLOOR: f64 = 2e10;
/// At least this many characters (`MinPasswordRunes`).
pub(crate) const MIN_CHARS: usize = 12;
/// At most this many bytes, in NFC (`MaxPasswordBytes`): the vault refuses a
/// longer password outright.
pub(crate) const MAX_BYTES: usize = 1024;

/// Why a passphrase is refused: the vault's `weak_password` reasons, plus
/// `TooLong` for what the vault would refuse as not a password at all.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Weakness {
    Short,
    Repeated,
    Common,
    Guessable,
    TooLong,
}

impl Weakness {
    /// The vault's reason string (`short`, `repeated`, `common`, `guessable`),
    /// and `too_long`.
    pub(crate) fn reason(self) -> &'static str {
        match self {
            Weakness::Short => "short",
            Weakness::Repeated => "repeated",
            Weakness::Common => "common",
            Weakness::Guessable => "guessable",
            Weakness::TooLong => "too_long",
        }
    }
}

const COMMON_LIST: &str = include_str!("passwords/common-passwords.txt");
const WORD_LIST: &str = include_str!("passwords/estimator-words.txt");

struct Lists {
    common: HashMap<String, u32>,
    words: HashMap<String, u32>,
}

fn lists() -> &'static Lists {
    static LISTS: OnceLock<Lists> = OnceLock::new();
    LISTS.get_or_init(|| Lists { common: load_list(COMMON_LIST), words: load_list(WORD_LIST) })
}

/// One entry per line, trimmed; blank lines and `#` comments skipped; the
/// rank is the entry's position, the first one kept (`loadList`).
fn load_list(text: &str) -> HashMap<String, u32> {
    let mut m = HashMap::new();
    let mut rank = 0;
    for line in text.lines() {
        let w = line.trim();
        if w.is_empty() || w.starts_with('#') {
            continue;
        }
        rank += 1;
        m.entry(w.to_string()).or_insert(rank);
    }
    m
}

/// Checks a passphrase already normalized to NFC (`passphrase::nfc`) against
/// the rule, at the apps' floor.
pub(crate) fn check(nfc: &str) -> Result<(), Weakness> {
    check_at(nfc, APP_FLOOR)
}

/// `CheckNewPassword` without the PIN rule, at a given floor.
fn check_at(nfc: &str, floor: f64) -> Result<(), Weakness> {
    if nfc.len() > MAX_BYTES {
        return Err(Weakness::TooLong);
    }
    let rs: Vec<char> = nfc.chars().collect();
    if rs.len() < MIN_CHARS {
        return Err(Weakness::Short);
    }
    if rs[1..].iter().all(|&c| c == rs[0]) {
        return Err(Weakness::Repeated);
    }
    if lists().common.contains_key(&nfc.to_ascii_lowercase()) {
        return Err(Weakness::Common);
    }
    if guesses(nfc) < floor {
        return Err(Weakness::Guessable);
    }
    Ok(())
}

// --- the estimator (password.go "the estimator") ---

const MIN_GUESSES_SINGLE: f64 = 10.0;
const MIN_GUESSES_MULTI: f64 = 50.0;
const BRUTEFORCE_CARD: f64 = 10.0;
const MAX_ESTIMATE_CHARS: usize = 128;
const MAX_PARTS: usize = 12;

/// Go's `unicode.ToLower`: the simple mapping. `char::to_lowercase` is the
/// full one, which differs only for U+0130 (to "i" and a combining dot); its
/// first character is the simple mapping.
fn lower(c: char) -> char {
    c.to_lowercase().next().unwrap_or(c)
}

/// Go's `unicode.ToUpper`: the simple mapping. Where the full mapping has
/// one character it is the simple one; where it has more, the simple
/// mapping leaves the character as it is, except for the Greek letters with
/// ypogegrammeni, which map to the forms with prosgegrammeni.
fn upper(c: char) -> char {
    let mut it = c.to_uppercase();
    match (it.next(), it.next()) {
        (Some(u), None) => u,
        _ => match c as u32 {
            0x1F80..=0x1F87 | 0x1F90..=0x1F97 | 0x1FA0..=0x1FA7 => char::from_u32(c as u32 + 8).unwrap_or(c),
            0x1FB3 => '\u{1FBC}',
            0x1FC3 => '\u{1FCC}',
            0x1FF3 => '\u{1FFC}',
            _ => c,
        },
    }
}

